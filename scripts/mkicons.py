#!/usr/bin/env python3
"""Generate mac/cdev/icons.r (the MoofTCP Finder and Control Panel icon family) from the parade
icon 'ICN#' 128 in mac/moof/moof.r.

    scripts/mkicons.py [-o mac/cdev/icons.r]

The 32x32 image and mask are copied to 'ICN#' -4064 (the icon the Finder and the Control Panel's
list show, through BNDL -4064). The colour icons are the same picture in black on white
('icl4'/'icl8': black = index 15 / 255, white = 0; System 6 ignores them, System 7 uses them);
the 16x16 family ('ics#', 'ics4', 'ics8') is a 2x2 downsample (a pixel is black if any of its four
source pixels is; the mask likewise). Re-run after changing the parade icon.
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def read_icn(path):
    s = open(path).read()
    m = re.search(r"data 'ICN#' \(128\) \{(.*?)\};", s, re.S)
    if not m:
        sys.exit("mkicons.py: no ICN# 128 in %s" % path)
    body = re.sub(r"/\*.*?\*/", "", m.group(1), flags=re.S)
    hx = "".join(re.findall(r'\$"([0-9A-Fa-f ]*)"', body)).replace(" ", "")
    b = bytes.fromhex(hx)
    if len(b) != 256:
        sys.exit("mkicons.py: ICN# 128 is %d bytes, not 256" % len(b))
    return b[:128], b[128:]


def bits(data, w):
    rb = w // 8
    return [[(data[y * rb + x // 8] >> (7 - x % 8)) & 1 for x in range(w)] for y in range(w)]


def pack(rows):
    out = bytearray()
    for r in rows:
        for x in range(0, len(r), 8):
            v = 0
            for k in range(8):
                v = (v << 1) | r[x + k]
            out.append(v)
    return bytes(out)


def down(rows):
    n = len(rows) // 2
    return [[rows[2 * y][2 * x] | rows[2 * y][2 * x + 1] | rows[2 * y + 1][2 * x] |
             rows[2 * y + 1][2 * x + 1] for x in range(n)] for y in range(n)]


def hexlines(b, per=16):
    return "\n".join('    $"%s"' % " ".join(b[i:i + per][k:k + 4].hex().upper()
                                          for k in range(0, len(b[i:i + per]), 4))
                     for i in range(0, len(b), per))


def depth(rows, d):
    if d == 8:
        return bytes(255 if p else 0 for r in rows for p in r)
    out = bytearray()
    for r in rows:
        for x in range(0, len(r), 2):
            out.append((15 if r[x] else 0) << 4 | (15 if r[x + 1] else 0))
    return bytes(out)


def main():
    out = os.path.join(ROOT, "mac/cdev/icons.r")
    a = sys.argv[1:]
    if len(a) == 2 and a[0] == "-o":
        out = a[1]
    elif a:
        sys.exit(__doc__)
    img, mask = read_icn(os.path.join(ROOT, "mac/moof/moof.r"))
    im, mk = bits(img, 32), bits(mask, 32)
    sim, smk = down(im), down(mk)
    parts = ["/* icons.r - generated by scripts/mkicons.py from 'ICN#' 128 in mac/moof/moof.r; do not edit. */",
             "", "data 'ICN#' (-4064) {", hexlines(img), "    /* mask */", hexlines(mask), "};",
             "", "data 'ics#' (-4064) {", hexlines(pack(sim) + pack(smk), 8), "};",
             "", "data 'icl4' (-4064) {", hexlines(depth(im, 4), 16), "};",
             "", "data 'icl8' (-4064) {", hexlines(depth(im, 8), 32), "};",
             "", "data 'ics4' (-4064) {", hexlines(depth(sim, 4), 8), "};",
             "", "data 'ics8' (-4064) {", hexlines(depth(sim, 8), 16), "};", ""]
    open(out, "w").write("\n".join(parts))
    print("wrote", out)


if __name__ == "__main__":
    main()
