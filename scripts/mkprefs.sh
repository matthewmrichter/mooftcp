#!/usr/bin/env bash
# Build the "MoofTCP Prefs" file (resource MCFG 128, format in mac/glue/mt_cfg.h) as MacBinary.
#   mkprefs.sh [--ip A] [--mask M] [--gw G] [--dns D] [--domain X] [--dhcp] [--log] [--tail HEX] [-o prefs.bin]
# --tail appends raw bytes after the flags byte (a future version's fields; tests that the control panel
# keeps them, Plan 3 Task 8); it implies the flags byte (00 without --log). --flags HEX writes that whole
# flags byte (2 hex digits; bit 0 = log; other bits are for tests that the panel keeps them, Task 11b).
# Every setting is optional (0 / empty = not set; no --ip leaves MoofTCP unconfigured). Default
# output: build-mac/prefs/MoofTCP Prefs.bin. Deploy it to the System Folder:
#   scripts/deploy.sh "build-mac/prefs/MoofTCP Prefs.bin" --to ":System Folder:"
# The file is type 'pref', creator 'ztcp'. Rez runs in the Retro68 container (scripts/r68).
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
die() { echo "mkprefs.sh: $*" >&2; exit 1; }
usage() { echo "usage: mkprefs.sh [--ip A] [--mask M] [--gw G] [--dns D] [--domain X] [--dhcp] [--log] [--flags HEX] [--tail HEX] [-o prefs.bin]" >&2; exit 2; }

ip=""; mask=""; gw=""; dns=""; domain=""; mode=0; out=""; log=0; tail=""; flagsarg=""
while [ $# -gt 0 ]; do
  case "$1" in
    --ip) [ $# -ge 2 ] || usage; ip="$2"; shift 2;;
    --mask) [ $# -ge 2 ] || usage; mask="$2"; shift 2;;
    --gw) [ $# -ge 2 ] || usage; gw="$2"; shift 2;;
    --dns) [ $# -ge 2 ] || usage; dns="$2"; shift 2;;
    --domain) [ $# -ge 2 ] || usage; domain="$2"; shift 2;;
    --dhcp) mode=1; shift;;
    --log) log=1; shift;;
    --flags) [ $# -ge 2 ] || usage; flagsarg="$2"; shift 2
             case "$flagsarg" in [0-9A-Fa-f][0-9A-Fa-f]) ;; *) die "--flags takes 2 hex digits";; esac;;
    --tail) [ $# -ge 2 ] || usage; tail="$2"; shift 2
            case "$tail" in *[!0-9A-Fa-f]*) die "--tail takes hex digits";; esac
            [ $(( ${#tail} % 2 )) -eq 0 ] || die "--tail needs whole bytes";;
    -o) [ $# -ge 2 ] || usage; out="$2"; shift 2;;
    *) usage;;
  esac
done

hexip() {  # dotted quad (or empty) -> 8 hex digits
  local a="$1" o1 o2 o3 o4
  [ -n "$a" ] || { echo 00000000; return; }
  [[ "$a" =~ ^([0-9]{1,3})\.([0-9]{1,3})\.([0-9]{1,3})\.([0-9]{1,3})$ ]] || die "bad address '$a'"
  o1=${BASH_REMATCH[1]}; o2=${BASH_REMATCH[2]}; o3=${BASH_REMATCH[3]}; o4=${BASH_REMATCH[4]}
  for o in $o1 $o2 $o3 $o4; do [ "$o" -le 255 ] || die "bad address '$a'"; done
  printf '%02X%02X%02X%02X' "$o1" "$o2" "$o3" "$o4"
}
[ ${#domain} -le 63 ] || die "domain longer than 63 characters"
case "$domain" in *[!A-Za-z0-9.-]*) die "domain may only contain A-Z a-z 0-9 . -";; esac

work="$ROOT/build-mac/prefs"
mkdir -p "$work"
flagshex=""; [ "$log" -eq 0 ] || flagshex="01"   # flags byte only with --log: the default file is unchanged
[ -z "$tail" ] || flagshex="$(printf '%02X' "$log")$tail"
[ -z "$flagsarg" ] || flagshex="$flagsarg$tail"
dhex="$(printf '%02X' ${#domain})$(printf '%s' "$domain" | od -An -tx1 | tr -d ' \n' | tr a-f A-F)"
cat > "$work/prefs.r" <<EOF
/* generated by scripts/mkprefs.sh */
data 'MCFG' (128) {
    \$"0001 $(printf '%04X' $mode)"
    \$"$(hexip "$ip") $(hexip "$mask") $(hexip "$gw") $(hexip "$dns")"
    \$"$dhex$flagshex"
};
EOF
rm -f "$work/MoofTCP Prefs.bin"
"$ROOT/scripts/r68" sh -c 'cd /src/build-mac/prefs && Rez prefs.r -o "MoofTCP Prefs.bin" -t pref -c ztcp' \
  2>&1 | grep -v '^Using multiversal' || true
[ -s "$work/MoofTCP Prefs.bin" ] || die "Rez produced nothing"
if [ -n "$out" ] && [ "$(readlink -f "$out" 2>/dev/null || echo "$out")" != "$(readlink -f "$work/MoofTCP Prefs.bin")" ]; then
  cp "$work/MoofTCP Prefs.bin" "$out"
else
  out="$work/MoofTCP Prefs.bin"
fi
echo "wrote $out (ip=${ip:-none} mask=${mask:-class} gw=${gw:-none} dns=${dns:-none} domain=${domain:-none} mode=$mode log=$log${tail:+ tail=$tail})"
