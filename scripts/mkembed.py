#!/usr/bin/env python3
"""Split the MoofTCP files into the resources the installer embeds (Plan 3 Task 10; one installer for
both variants since the "Lite checkbox" follow-up, docs/dev/DHCP-DESIGN.md section 10).

    scripts/mkembed.py <out-dir> <full MoofTCP.bin> <Lite MoofTCP.bin>

For each file (id 128 = MoofTCP, the full build; id 129 = MoofTCP Lite) writes into <out-dir>:
    MoofTCP-<id>.rfork  the resource fork, byte for byte (becomes resource 'MTCP' <id>)
    MoofTCP-<id>.dfork  the data fork (resource 'MTCD' <id>, only when it is not empty; the release has none)
and one Rez source embed.r: 'MTCP' / 'MTCD' <id> by $$read of the files above, and 'MTCI' <id> =
type (4) + creator (4) + Finder flags (2) of the file, big-endian.
The installer writes the forks of the chosen one into the new file and sets type, creator and flags
from MTCI (scripts/mbflags.py has set hasBundle 0x2000 in the .bin). The 'vers' 1 inside each
resource fork is what the installer compares with an installed MoofTCP; its long string names the
variant ("MoofTCP Lite ..."), which this script checks: the full file must not say Lite, the Lite
file must (a swapped or stale build tree fails here, not on the Mac). Both short strings must agree.
Generated at build time; never committed.
"""
import importlib.util
import os
import struct
import sys

here = os.path.dirname(os.path.abspath(__file__))
spec = importlib.util.spec_from_file_location("resmap", os.path.join(here, "resmap.py"))
resmap = importlib.util.module_from_spec(spec)
spec.loader.exec_module(resmap)


def split(src):
    d = open(src, "rb").read()
    if len(d) < 128 or d[0] != 0 or d[74] != 0:
        sys.exit("mkembed.py: %s is not a MacBinary file" % src)
    ftype, creator = d[65:69], d[69:73]
    flags = (d[73] << 8) | d[101]
    dlen, rlen = struct.unpack(">II", d[83:91])
    doff = 128
    roff = 128 + ((dlen + 127) // 128) * 128
    dfork, rfork = d[doff:doff + dlen], d[roff:roff + rlen]
    if len(dfork) != dlen or len(rfork) != rlen or rlen == 0:
        sys.exit("mkembed.py: %s is truncated or has no resource fork" % src)
    flags &= ~0x0101                     # never ship hasBeenInited / onDesk: the Finder sets them
    return ftype, creator, flags, dfork, rfork


def vers1(rfork, src):
    for t, rid, _nm, _size, _attr, data in resmap.resources(rfork):
        if t == "vers" and rid == 1:
            n = data[6]
            m = data[7 + n]
            return data[7:7 + n].decode("mac_roman"), data[8 + n:8 + n + m].decode("mac_roman")
    sys.exit("mkembed.py: no 'vers' 1 in %s" % src)


def main():
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    out = sys.argv[1]
    os.makedirs(out, exist_ok=True)
    lines = ["/* embed.r - generated by scripts/mkembed.py; do not edit. 128 = MoofTCP, 129 = MoofTCP Lite. */"]
    shorts = []
    for rid, src in ((128, sys.argv[2]), (129, sys.argv[3])):
        ftype, creator, flags, dfork, rfork = split(src)
        short, long_ = vers1(rfork, src)
        lite = long_.startswith("MoofTCP Lite")
        if lite != (rid == 129):
            sys.exit("mkembed.py: %s has the long version %r; id %d needs %s" %
                     (src, long_, rid, "MoofTCP Lite" if rid == 129 else "the full MoofTCP"))
        shorts.append(short)
        name = "MoofTCP Lite" if rid == 129 else "MoofTCP"
        rpath = os.path.join(out, "MoofTCP-%d.rfork" % rid)
        dpath = os.path.join(out, "MoofTCP-%d.dfork" % rid)
        open(rpath, "wb").write(rfork)
        open(dpath, "wb").write(dfork)
        info = ftype + creator + struct.pack(">H", flags)
        lines.append("data 'MTCP' (%d, \"%s\") { $$read(\"%s\") };" % (rid, name, rpath))
        if dfork:
            lines.append("data 'MTCD' (%d, \"%s\") { $$read(\"%s\") };" % (rid, name, dpath))
        lines.append("data 'MTCI' (%d, \"%s\") { $\"%s\" };" % (rid, name, info.hex().upper()))
    if shorts[0] != shorts[1]:
        sys.exit("mkembed.py: the two MoofTCP files have different versions (%r, %r)" % tuple(shorts))
    tmp = os.path.join(out, "embed.r.new")
    open(tmp, "w").write("\n".join(lines) + "\n")
    os.replace(tmp, os.path.join(out, "embed.r"))


if __name__ == "__main__":
    main()
