#!/usr/bin/env python3
"""Split a MacBinary file into the resources the installer embeds (Plan 3 Task 10).

    scripts/mkembed.py <MoofTCP.bin> <out-dir>

Writes into <out-dir>:
    MoofTCP.rfork   the resource fork, byte for byte (becomes resource 'MTCP' 128 "MoofTCP")
    MoofTCP.dfork   the data fork (resource 'MTCD' 128, only when it is not empty; the release has none)
    embed.r         Rez source: 'MTCP' 128 and 'MTCD' 128 by $$read of the files above, and
                    'MTCI' 128 = type (4) + creator (4) + Finder flags (2) of the file, big-endian.
The installer writes the forks into the new file and sets type, creator and flags from MTCI
(scripts/mbflags.py has set hasBundle 0x2000 in the .bin). The 'vers' 1 inside the resource fork is
what the installer compares with an installed MoofTCP. Generated at build time; never committed.
"""
import os
import struct
import sys


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    src, out = sys.argv[1], sys.argv[2]
    d = open(src, "rb").read()
    if len(d) < 128 or d[0] != 0 or d[74] != 0:
        sys.exit("mkembed.py: %s is not a MacBinary file" % src)
    ftype, creator = d[65:69], d[69:73]
    flags = (d[73] << 8) | d[101]
    dlen, rlen = struct.unpack(">II", d[83:91])
    doff = 128
    roff = 128 + ((dlen + 127) // 128) * 128
    dfork, rfork = d[doff:doff + dlen], d[roff:roff + rlen]
    if len(dfork) != dlen or len(rfork) != rlen or rlen == 0:
        sys.exit("mkembed.py: %s is truncated or has no resource fork" % src)
    flags &= ~0x0101                     # never ship hasBeenInited / onDesk: the Finder sets them
    os.makedirs(out, exist_ok=True)
    rpath = os.path.join(out, "MoofTCP.rfork")
    dpath = os.path.join(out, "MoofTCP.dfork")
    open(rpath, "wb").write(rfork)
    open(dpath, "wb").write(dfork)
    info = ftype + creator + struct.pack(">H", flags)
    lines = ["/* embed.r - generated by scripts/mkembed.py from %s; do not edit. */" % os.path.basename(src),
             "data 'MTCP' (128, \"MoofTCP\") { $$read(\"%s\") };" % rpath]
    if dlen:
        lines.append("data 'MTCD' (128, \"MoofTCP\") { $$read(\"%s\") };" % dpath)
    lines.append("data 'MTCI' (128, \"MoofTCP\") { $\"%s\" };" % info.hex().upper())
    tmp = os.path.join(out, "embed.r.new")
    open(tmp, "w").write("\n".join(lines) + "\n")
    os.replace(tmp, os.path.join(out, "embed.r"))


if __name__ == "__main__":
    main()
