struct mt_stack {
    mt_ifconfig cfg;
    mt_link link;
    mt_limits lim;
    mt_stats stats;
    uint32_t seed;           /* ISN base (mt_set_entropy a) */
    uint32_t key;            /* ISN tuple-mix key (mt_set_entropy b); 0 = no mix */
    /* arena sections */
    mt_arp_entry *arp;       /* lim.arp_entries entries */
    mt_pending *pend;
    mt_reasm *reasm;
    mt_lo *lo;               /* loopback FIFO */
    mt_udp *udp;             /* lim.max_udp app endpoints + 1 reserved for DNS (last) */
    mt_tcp *tcp;             /* lim.max_tcp TCBs */
    mt_dns *dns;
    mt_dns_cent *dcache;     /* lim.dns_cache entries */
    mt_logrec *log;          /* MT_LOG_RECS records (arena section) */
    /* Free-running counters, modulo 65536 (a multiple of MT_LOG_RECS); record index = counter &
     * (MT_LOG_RECS - 1). volatile: the writer may be an interrupt handler and the reader main
     * code. Assumption: exactly one writer context (log_wr) and one reader context (log_rd). */
    volatile uint16_t log_wr, log_rd;
    uint8_t log_on;
    uint8_t tx_refused;      /* set by mt_eth_send when the link refused the frame; senders that care
                              * (TCP) clear it before building a frame and read it afterwards */
    uint8_t stall_on;        /* stall_at is armed: some TCB has MT_T2_STALL */
    uint32_t stall_at;       /* absolute ms of the next stall retry (one timer for all TCBs) */
    uint32_t now;            /* last clock value seen by mt_input / mt_tick / mt_dns_query */
    uint16_t tcp_eph;        /* next ephemeral TCP port candidate */
    uint16_t lis_eph;        /* next candidate for a port-0 listen (1024..2047) */
    /* The TCP segment (if any) that mt_arp_insert just released from the held slot; consulted
     * and cleared by mt_tcp_arp_resolved so it does not retransmit that same segment. */
    struct { mt_ip4 dst; uint32_t seq; uint16_t sport, dport, len; uint8_t live; } arp_rel;
    uint16_t udp_eph;        /* next ephemeral port candidate */
    uint16_t ip_id;          /* next IPv4 identification */
    uint32_t icmp_err_next;  /* earliest time (ms) the next ICMP error we originate may be sent */
    mt_echo_cb echo_cb;
    void *echo_user;
#ifdef MT_TEST_HOOKS
    mt_ip_spy_fn ip_spy;
    void *ip_spy_ctx;
    void (*icmp_err_spy)(void *ctx, uint8_t proto, mt_ip4 dst, uint16_t lport, uint16_t rport,
                         uint8_t type, uint8_t code);
    void *icmp_err_ctx;
    void (*log_put_spy)(mt_stack *s);   /* called inside mt_log_put after the time is stored,
                                         * before the rest of the record and before log_wr moves */
#endif
    /* scratch */
    uint8_t txbuf[MT_TXBUF_SIZE];   /* upper layers build at txbuf + 14 */
    uint8_t arpbuf[60];             /* ARP requests/replies, kept apart from txbuf */
};

/* ---- Diagnostic log (mt_stack.c) ----
 * mt_log() is the only call sites use: one load + branch while the log is off. */
/* Compiler-only barrier: keeps record accesses on the correct side of the log_wr accesses. */
#if defined(__GNUC__)
#define MT_BARRIER() __asm__ volatile("" ::: "memory")
#else
#define MT_BARRIER() ((void)0)
#endif
void mt_log_put(mt_stack *s, uint8_t code, uint8_t a, uint16_t b);
static inline void mt_log(mt_stack *s, uint8_t code, uint8_t a, uint16_t b) {
    if (s->log_on) mt_log_put(s, code, a, b);
}
/* A packet was refused for the reason at this source line (b = __LINE__). Use together with the
 * drop counter. In input functions that `goto drop`, MT_DROP_GOTO records the line of the
 * failing check in the local `why`. */
#define MT_LOG_DROPPED(s, layer, line) mt_log((s), MT_LOG_DROP, (layer), (uint16_t)(line))
/* Count an IPv4-layer drop (ip_in_drops) and log it with the line of this statement. */
#define MT_DROP_IP(s) do { (s)->stats.ip_in_drops++; MT_LOG_DROPPED((s), MT_LOGL_IP, __LINE__); } while (0)
#define MT_DROP_GOTO(why) do { (why) = (uint16_t)__LINE__; goto drop; } while (0)

