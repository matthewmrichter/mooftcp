uint32_t mt_tcp_deadline(const mt_stack *s, uint32_t now);
/* An ARP entry for `ip` just resolved: every connection whose next hop is `ip` and that has
 * unacked data goes back to snd_una (go-back-N, bounded by cwnd) and resends, except for the
 * segment mt_arp_insert released from the held slot a moment ago (s->arp_rel, set by
 * mt_tcp_note_released), which is on the wire already and is skipped. */
void mt_tcp_arp_resolved(mt_stack *s, mt_ip4 ip, uint32_t now);
void mt_tcp_note_released(mt_stack *s, const uint8_t *iphdr);   /* held frame about to be sent */
/* Transmit whatever the state permits: SYN / SYN-ACK, queued data within the peer window,
 * FIN, or a pending ACK. Single decision point; every sender goes through it. */
void mt_tcp_output(mt_tcp *t, uint32_t now);
/* Window to advertise now: the receive ring's free space, except that growth smaller than
 * min(mss, ring/2) over the last advertised edge is withheld (receiver SWS avoidance). With
 * `commit` the advertised edge is recorded. Never shrinks an advertised window. */
uint32_t mt_tcp_rcv_window(mt_tcp *t, int commit);
/* Build and send one segment of t: seq, flags (ACK is added/ack filled from rcv_nxt when the
 * MT_TH_ACK bit is set), n payload bytes copied (and checksummed in the same pass) from the send
 * queue, starting off bytes past snd_una. Returns nonzero if the link refused the frame (counted
 * in tcp_tx_stalls; an owed ACK then stays owed). */
int mt_tcp_xmit(mt_tcp *t, uint32_t seq, uint8_t flags, uint32_t off, uint32_t n, uint32_t now);
/* Retransmit the first unacked segment (SYN, SYN-ACK, data from the send queue, or FIN). */
void mt_tcp_rexmit(mt_tcp *t, uint32_t now);
/* Zero-window probe: one byte of the first unsent data (does not advance snd_nxt). */
void mt_tcp_probe(mt_tcp *t, uint32_t now);
/* RTO from the RFC 6298 state (srtt + 4*rttvar, clamped), INIT while nothing is measured. */
static inline uint32_t mt_tcp_rto_base(const mt_tcp *t) {
    uint32_t r;
    if (t->srtt8 == 0) return MT_TCP_RTO_INIT;
    r = (t->srtt8 >> 3) + t->rttvar4;
    return r < MT_TCP_RTO_MIN ? MT_TCP_RTO_MIN : r > MT_TCP_RTO_MAX ? MT_TCP_RTO_MAX : r;
}
/* Segment without a TCB (reset replies) or with explicit fields. */
void mt_tcp_send_raw(mt_stack *s, mt_ip4 rip, uint16_t lport, uint16_t rport, uint32_t seq,
                     uint32_t ack, uint8_t flags, uint32_t now);
uint16_t mt_tcp_local_mss(const mt_stack *s);
/* Local MSS toward rip: MT_LO_MTU - 40 (536) for a loopback peer, else mt_tcp_local_mss. */
uint16_t mt_tcp_local_mss_to(const mt_stack *s, mt_ip4 rip);
/* Bytes queued from snd_una on (unacked + unsent data; completed requests hold 0). */
static inline uint32_t mt_tcp_sq_total(const mt_tcp *t) {
    return t->sq_n == 0 ? 0u : t->sq_n == 1 ? t->sq[0].left : t->sq[0].left + t->sq[1].left;
}
/* Data bytes sent and not yet ACKed: snd_max - snd_una without the FIN's sequence number while
 * the FIN is outstanding (an ACKed FIN leaves 0, never -1). */
static inline uint32_t mt_tcp_data_out(const mt_tcp *t) {
    uint32_t out = t->snd_max - t->snd_una;
    return ((t->flags & MT_TF_FINSENT) && out) ? out - 1u : out;
}
static inline uint32_t mt_tcp_pseudo(mt_ip4 src, mt_ip4 dst, uint16_t len) {
    return (src >> 16) + (src & 0xFFFFu) + (dst >> 16) + (dst & 0xFFFFu) + 6u + len;
}

