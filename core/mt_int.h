/* Single frame held while its next hop resolves (len == 0: empty). Only small
 * frames wait on ARP (SYN, DNS query, ICMP echo, first UDP datagram); larger
 * ones are dropped and recovered by upper-layer retransmission. */
#define MT_PEND_MAX 256u   /* frame bytes including the 14-byte Ethernet header */
typedef struct {
    mt_ip4 nexthop;
    uint16_t len;
    uint8_t frame[MT_PEND_MAX];
} mt_pending;

/* ---- IPv4 reassembly: one slot, payload buffer in the arena ---- */
#define MT_REASM_MAX 4096u
#define MT_REASM_UNITS (MT_REASM_MAX / 8u)       /* 512 bits of 8-byte units */
#define MT_REASM_TIMEOUT_MS 15000u
typedef struct {
    uint32_t bitmap[MT_REASM_UNITS / 32u];
    uint32_t t_start;
    mt_ip4 src;
    uint16_t id;
    uint16_t got;        /* units received */
    uint16_t total;      /* payload length once the last fragment is seen, else 0 */
    uint16_t maxend;     /* highest byte offset covered so far */
    uint8_t proto;
    uint8_t active;
    uint8_t buf[MT_REASM_MAX];
} mt_reasm;

/* ---- Loopback: datagrams to our own address (cfg.addr or 127.0.0.0/8) ----
 * mt_ip_output* never puts them on the wire: each IPv4 datagram (or fragment) is copied into a
 * FIFO of MT_LO_SLOTS slots and fed to the IPv4 input path by mt_tick (mt_ip_lo_drain), never from
 * inside the output call (mt_input / mt_tick must not be re-entered). While a slot is queued
 * mt_next_deadline is 0. A drain delivers only the frames queued when it started, so every hop of
 * a self connection costs one tick and a reply generated by a delivered frame waits for the next
 * drain (bounded work per tick; no ping-pong inside one call). The slot being delivered stays
 * reserved until its dispatch returns, so a reply always lands in another slot. A full FIFO is a
 * refusal exactly like a refused link.tx (s->tx_refused, ip_lo_drops): TCP stalls and retries.
 * MT_LO_MTU is the loopback interface MTU (the frame never leaves the machine): 576, the datagram
 * size every IPv4 host must accept (RFC 791 / RFC 1122 EMTU_R); a self connection uses MSS 536,
 * larger datagrams are fragmented into the FIFO, all fragments or none: more than MT_LO_SLOTS
 * fragments (an IP payload over 1656 bytes) is MT_ERR_INVAL, more than the free slots is one
 * refusal (ip_lo_drops counts datagrams refused, not fragments). */
#define MT_LO_MTU   576u
#define MT_LO_SLOTS 3u
typedef struct {
    uint16_t len;
    uint8_t d[MT_LO_MTU];        /* the IPv4 datagram, header included (no Ethernet header) */
} mt_lo_slot;
typedef struct {
    uint8_t head, n;             /* oldest slot; slots queued (incl. one being delivered) */
    uint8_t dlv;                 /* 1 while slot `head` is being delivered */
    uint8_t left;                /* frames the running drain may still deliver (flush: 0) */
    mt_lo_slot s[MT_LO_SLOTS];
} mt_lo;

