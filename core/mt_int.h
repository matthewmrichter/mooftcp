/* ---- UDP endpoint (arena array of lim.max_udp + 1; port 0 = free slot; the last slot is
 * reserved for the DNS resolver, apps use slots 0..max_udp-1) ----
 * Receive area: records [src(4) sport(2) len(2) data] padded to even, placed contiguously
 * in the caller's buf. head/tail are byte offsets; when a record does not fit before the
 * end, `wrap` remembers where the tail run stopped and the next record starts at 0.
 * Datagrams are given back in any order (mt_udp_done_at): a given-back record keeps its place,
 * marked src = 0xFFFFFFFF, until every older record is back; the head record is never marked. */
struct mt_udp {
    mt_stack *st;
    uint8_t *buf;
    uint32_t buflen, head, tail, wrap;
    mt_udp_cb cb;
    void *user;
    uint16_t port;
    uint16_t n;          /* records in the ring (queued datagrams, including given-back ones) */
    uint16_t nret;       /* records given back out of order but still in the ring (src = UDP_RET) */
};

/* ---- TCP (mt_tcp.c lifecycle + input, mt_tcp_out.c segment output) ----
 * TCBs live in an arena array (lim.max_tcp; used == 0 is a free slot). Sequence variables follow
 * RFC 793. Fields are ordered hot first.
 * Send queue: up to MT_SENDQ_MAX caller requests (mt_tcp_send_segs), FIFO, holding the bytes from
 * snd_una on (unacked first, then unsent) in caller memory; nothing is copied until a segment is
 * built. `left` counts a request's bytes not yet acknowledged; a request with left == 0 is
 * complete and waits at the head only until its done callback is fired (same call). The cursor
 * (sq_idx, sq_off) is the position of snd_una inside the first request with left > 0 (0, 0 if
 * none). The FIN, once sent, occupies the last sequence number but no queued byte. */
typedef struct {
    const mt_seg *segs;       /* the caller's segment array (read-only) */
    mt_send_done_cb done;
    void *ud;
    uint32_t left;            /* bytes not yet acknowledged */
    uint8_t nsegs, push;
} mt_sendreq;
enum { MT_TT_RTO, MT_TT_DELACK, MT_TT_PERSIST, MT_TT_TW, MT_TT_N };   /* tmr[] slots / tmask bits */
#define MT_TF_ACKNOW   0x01u   /* an ACK is owed: mt_tcp_output sends one if nothing carries it */
#define MT_TF_FINQ     0x02u   /* app closed: send FIN after the queued data */
#define MT_TF_FINSENT  0x04u   /* FIN transmitted at least once (occupies seq snd_max-1) */
#define MT_TF_PASSIVE  0x08u   /* SYN_RCVD reached from LISTEN: RST/timeout re-listens */
#define MT_TF_EST      0x10u   /* counted in stats.tcp_conns_open */
#define MT_TF_ULPABORT 0x20u   /* ULP timeout aborts (else only fires the event) */
#define MT_TF_STALLIDLE 0x40u  /* the output pass cut short by a refusal started idle (Nagle) */
/* flags2 */
#define MT_T2_ACKHALF  0x01u   /* one full-size segment received and not yet ACKed (ack every 2nd) */
#define MT_T2_INPUT    0x02u   /* inside in_sync for this TCB (mt_input): its own post-callback output
                                * decides the ACK; rcv_freed must not send the delayed one */
#define MT_T2_STALL    0x04u   /* the last output pass ended on a refused data/FIN segment: the
                                * stack's stall timer (s->stall_at) retries it */
#define MT_T2_SNDURG   0x08u   /* snd_up is live: segments before it carry URG */
#define MT_T2_RCVURG   0x10u   /* rcv_up is live: unread urgent data may remain */
#define MT_T2_RTTING   0x20u   /* rtt_seq/rtt_t0 hold a timed (never retransmitted) segment */
#define MT_T2_RECOV    0x40u   /* in fast recovery (until ACK >= recover) */
#define MT_T2_GAP      0x80u   /* data seen beyond rcv_nxt: ACK every in-order segment until rcv_nxt >= ooo_hi */
#define MT_TH_FIN 0x01u
#define MT_TH_SYN 0x02u
#define MT_TH_RST 0x04u
#define MT_TH_PSH 0x08u
#define MT_TH_ACK 0x10u
#define MT_TH_URG 0x20u
#define MT_TCP_DELACK_MS 100u
#define MT_TCP_STALL_MS  10u   /* retry delay after the link refused a data/FIN segment */
#define MT_TCP_QUICKACK  4u    /* the first data segments of a connection are ACKed at once */
#define MT_TCP_RTO_INIT 1000u
#define MT_TCP_RTO_MAX  60000u
#define MT_TCP_RTO_MIN  1000u  /* RFC 6298 2.4; RC2 hardware: the DaynaPORT link holds frames up to ~500 ms, 200 fired spuriously */
/* FIN_WAIT_2 backstop: 600 s of silence from the peer (any acceptable segment refreshes it).
 * At expiry it acts like the ULP timeout: ULP_TIMEOUT event, abort only if the abort flag is set. */
#define MT_TCP_FW2_MS   600000u
struct mt_tcp {
    mt_stack *st;
    uint32_t snd_una, snd_nxt, snd_wnd, rcv_nxt;
    uint32_t snd_max;         /* highest sequence ever sent (snd_nxt is pulled back to snd_una by
                               * go-back-N recovery; ACKs are valid up to snd_max) */
    mt_ring rcvq;             /* the whole mt_tcp_create buffer */
    uint32_t snd_wl1, snd_wl2, iss, irs;
    uint32_t ooo_hi;          /* end of the highest out-of-order segment seen (valid while MT_T2_GAP) */
    uint32_t rcv_adv;         /* right edge of the window last advertised (receiver SWS) */
    uint32_t rcv_up, snd_up;  /* urgent marks: sequence number just past the urgent data */
    uint32_t tmr[MT_TT_N];    /* absolute ms deadlines, valid where the tmask bit is set */
    uint32_t rto;             /* ms, current (backed-off) retransmission timeout */
    uint32_t srtt8, rttvar4;  /* RFC 6298 state in fixed point: srtt*8, rttvar*4 (ms); srtt8 0 = unmeasured */
    uint32_t cwnd, ssthresh, ca_acc;   /* congestion window; bytes acked toward the next CA step */
    uint32_t recover;         /* snd_max when loss recovery began (NewReno) */
    uint32_t rtt_seq, rtt_t0; /* timed segment: ACK >= rtt_seq yields a sample (t0 = send time) */
    uint32_t ulp_dl;          /* absolute ULP deadline (valid while RTO or PERSIST is armed) */
    uint32_t ulp_ms;          /* ULP timeout in ms, 0 = none */
    uint32_t tnow;            /* last clock value seen (for APIs without a `now` argument) */
    mt_ip4 rip, frip;         /* peer; listen filter */
    mt_tcp_cb cb;
    void *user;
    mt_sendreq sq[MT_SENDQ_MAX];   /* send queue, FIFO (see above) */
    uint16_t sq_off;               /* cursor: byte offset of snd_una in segs[sq_idx] */
    uint8_t sq_idx, sq_n;          /* cursor segment index; requests queued (incl. completed ones) */
    uint16_t lport, rport, flport, frport;   /* connection; listen filters (0 = any) */
    uint16_t mss;
    uint16_t rcv_mss;         /* largest payload received in one segment (clamped to the local MSS) */
    uint8_t state, flags, flags2, tmask, used, dupacks;
    uint8_t gen;              /* bumped on create/release/terminate/abort: stale deferred events are dropped */
    uint8_t qack;             /* data segments received on this connection, saturating at MT_TCP_QUICKACK */
};


/* ---- DNS (mt_dns.c) ----
 * One lazily created UDP endpoint (rx buffer inside the arena), MT_DNS_SLOTS concurrent
 * queries, and a lim.dns_cache entry cache (separate arena section). The query name is kept
 * once per slot (256 bytes) so retries and response validation can rebuild it. */
#define MT_DNS_SLOTS 4u
#define MT_DNS_RXBUF 1024u
#define MT_DNS_CNAME 64u         /* cache key / canonical name capacity (63 chars + NUL) */
typedef struct {
    char name[MT_DNS_CNAME];     /* key: the name as queried (lower case) */
    char canon[MT_DNS_CNAME];    /* canonical name from the answer */
    mt_ip4 addr[MT_DNS_MAXADDR];
    uint32_t exp;                /* absolute ms expiry */
    uint32_t used;               /* ms stamp of last use (LRU) */
    uint8_t naddr;               /* 0 = free */
    uint8_t ptr;                 /* 1 = reverse (PTR) entry: addr[0] is the key, canon the name */
} mt_dns_cent;
typedef struct {
    mt_dns_result *out;          /* NULL for a reverse lookup */
    char *pbuf;                  /* mt_dns_ptr: the caller's name buffer */
    mt_dns_ptr_cb pcb;
    mt_dns_cb cb;
    void *user;
    mt_ip4 paddr;                /* mt_dns_ptr: the address asked about */
    uint16_t pcap;
    uint32_t t0;                 /* time the current question was first sent */
    uint16_t id;
    uint8_t used, qtype, tries, dom;   /* tries = retransmissions done; dom = domain appended */
    char name[MT_DNS_NAMELEN + 1];     /* as queried, no trailing dot */
} mt_dns_q;
typedef struct {
    mt_udp *udp;                 /* NULL until the first network query */
    uint32_t rnd;                /* xorshift32 state for query IDs */
    mt_dns_q q[MT_DNS_SLOTS];
    char pname[MT_DNS_NAMELEN + 1];   /* scratch name of the one reverse lookup in flight */
    uint8_t rx[MT_DNS_RXBUF];
} mt_dns;
void mt_dns_timers(mt_stack *s, uint32_t now);
/* The resolver's endpoint lives in the reserved slot after the app endpoints. */
mt_udp *mt_udp_create_reserved(mt_stack *s, uint16_t lport, uint8_t *buf, uint32_t buflen,
                               mt_udp_cb cb, void *user);
void mt_dns_reseed(mt_stack *s, uint32_t a, uint32_t b);
